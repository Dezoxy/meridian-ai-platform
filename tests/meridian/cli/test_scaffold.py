def leave_the_root_at(root: Path, relative: str, outside: Path) -> None:
    """Make ``relative`` a symbolic link to the directory ``outside`` the root."""
    path = root / relative
    if path.is_dir():
        shutil.rmtree(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.symlink_to(outside, target_is_directory=True)


@pytest.mark.parametrize(
    "relative",
    [
        "src/meridian/workloads",
        "config/registry",
        "data/evaluation",
        "data",
        "tests/meridian/workloads",
        "tests/meridian",
        "tests",
    ],
)
def test_a_directory_the_workload_is_written_to_that_leaves_the_checkout_is_refused(
    root: Path, tmp_path_factory: pytest.TempPathFactory, relative: str
) -> None:
    outside = tmp_path_factory.mktemp("outside")
    (outside / "agents.yaml").write_bytes(
        (root / "config/registry/agents.yaml").read_bytes()
    )
    leave_the_root_at(root, relative, outside)
    if relative == "config/registry":  # the registry is read through the link
        shutil.copytree(REPO / "config/registry", outside, dirs_exist_ok=True)
    before = snapshot(root)
    outside_before = snapshot(outside)

    with pytest.raises(ScaffoldError) as refused:
        plan_workload(root, NAME)

    assert str(refused.value) == PATH_OUTSIDE
    assert snapshot(root) == before
    assert snapshot(outside) == outside_before


