def test_every_refusal_text_is_fixed_and_only_those_that_take_a_type_hold_a_field() -> (
    None
):
    texts = [
        BAD_NAME,
        AMBIGUOUS_NAME,
        NOT_A_CHECKOUT,
        REGISTRY_INVALID,
        NAME_TAKEN,
        AGENTS_EDIT_UNVERIFIED,
        AGENTS_LIST_UNUSABLE,
        PYPROJECT_EDIT_UNVERIFIED,
        PYPROJECT_HEADER_UNUSABLE,
        PYPROJECT_NOT_TOML,
        PATH_EXISTS,
        STALE_PLAN,
        REGISTRY_UNREADABLE,
        REGISTRY_EDIT_INVALID,
        REGISTRY_COPY_FAILED,
        WRITE_FAILED,
        ROLLBACK_FAILED,
    ]
    # The first four take the type of an error; the last three take what the
    # refusal says of the person's own tree: what holds a name, a line, a header.
    taking_a_type = {
        REGISTRY_UNREADABLE,
        REGISTRY_COPY_FAILED,
        WRITE_FAILED,
        ROLLBACK_FAILED,
        NAME_TAKEN,
        AGENTS_LIST_UNUSABLE,
        PYPROJECT_HEADER_UNUSABLE,
    }
    assert len(set(texts)) == len(texts)
    assert all(text.strip() for text in texts)
    assert {text for text in texts if "{}" in text} == taking_a_type
    assert all("{" not in text for text in texts if text not in taking_a_type)


