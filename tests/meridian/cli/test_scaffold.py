def test_each_entry_point_follows_its_tables_last_key_line(root: Path) -> None:
    old = (root / "pyproject.toml").read_text(encoding="utf-8")

    plan = plan_workload(root, NAME)

    new = plan.changed["pyproject.toml"]
    # The last key of each table as the file has it today, whatever workloads it
    # lists: a tree with a second workload must not fail this test.
    tables = tomllib.loads(old)["project"]["entry-points"]
    last_graph, graph_value = list(tables[GRAPHS].items())[-1]
    last_evaluation, evaluation_value = list(tables[EVALUATIONS].items())[-1]
    graph_old = f'{last_graph} = "{graph_value}"\n'
    graph_new = f'{NAME} = "meridian.workloads.{MODULE}.graph:build"\n'
    evaluation_old = f'{last_evaluation} = "{evaluation_value}"\n'
    evaluation_new = f'{NAME} = "meridian.workloads.{MODULE}.evaluation:EVALUATION"\n'
    assert old.count(graph_old) == 1 and old.count(evaluation_old) == 1
    assert new == old.replace(graph_old, graph_old + graph_new).replace(
        evaluation_old, evaluation_old + evaluation_new
    )
    # The blank line and the comment that followed the graphs table stay after
    # the inserted key.
    assert graph_new + "\n# `meridian eval run`" in new


MINIMAL_PYPROJECT = (
    '[project]\nname = "meridian"\n\n'
    '[project.entry-points."meridian.graphs"]\nclaims-triage = "a.b:c"\n\n'
    "# a comment that belongs to the next table\n"
    '[project.entry-points."meridian.evaluations"]\nclaims-triage = "d.e:f"'
)


@pytest.mark.parametrize("line_ending", ["\n", "\r\n"], ids=["lf", "crlf"])
def test_the_line_endings_and_a_missing_final_newline_are_kept(
    root: Path, line_ending: str
) -> None:
    text = MINIMAL_PYPROJECT.replace("\n", line_ending)
    (root / "pyproject.toml").write_bytes(text.encode("utf-8"))
    graph_old = 'claims-triage = "a.b:c"'
    graph_new = f'{NAME} = "meridian.workloads.{MODULE}.graph:build"'
    evaluation_old = 'claims-triage = "d.e:f"'
    evaluation_new = f'{NAME} = "meridian.workloads.{MODULE}.evaluation:EVALUATION"'

    plan = plan_workload(root, NAME)

    # The inserted line takes the file's line ending, and the last line, which
    # had none, still has none.
    assert plan.changed["pyproject.toml"] == text.replace(
        graph_old, graph_old + line_ending + graph_new, 1
    ).replace(evaluation_old, evaluation_old + line_ending + evaluation_new, 1)


